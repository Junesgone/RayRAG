import { chromium } from "playwright-core";
const ORIGIN = "http://127.0.0.1:9390";
const PASSWORD = process.env.RAYRAG_LOGIN_PASSWORD;
const b = await chromium.connectOverCDP("http://127.0.0.1:16002");
const ctx = b.contexts()[0];
const page = await ctx.newPage();
const errs = [];
page.on("pageerror", (e) => errs.push(String(e.message)));
await page.goto(ORIGIN + "/login", { waitUntil: "domcontentloaded" });
await page.evaluate(async (password) => {
  const res = await fetch("/api/v1/auth/login", {method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({email:"admin@rayrag.local",password})});
  const data = await res.json();
  localStorage.setItem("rayrag_token", data.data.access_token);
  document.cookie = "rayrag_token=" + data.data.access_token + ";path=/";
}, PASSWORD);
await page.goto(ORIGIN + "/admin/sandbox-settings", { waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-testid='admin-sandbox-provider-self_managed']");
await page.waitForSelector("#sbConfigCard:not([hidden])");
console.log("initial title:", await page.locator("#sbConfigTitle").innerText());
await page.locator("[data-testid='admin-sandbox-provider-local']").click();
await page.waitForTimeout(1200);
console.log("after local:", await page.locator("#sbConfigTitle").innerText());
await page.locator("[data-testid='admin-sandbox-test']").click();
await page.waitForSelector("[data-testid='admin-sandbox-test-message']", { timeout: 60000 });
console.log("test msg:", (await page.locator("[data-testid='admin-sandbox-test-message']").innerText()).slice(0, 60));
await page.locator("#sbTestModal .ds-dialog-footer button").click();
await page.waitForTimeout(500);
console.log("modal classes:", await page.evaluate(() => document.getElementById("sbTestModal").className));
await page.locator("[data-testid='admin-sandbox-provider-self_managed']").click();
await page.waitForTimeout(1500);
console.log("after self_managed click:", await page.locator("#sbConfigTitle").innerText());
console.log("state:", await page.evaluate(() => JSON.stringify({provider: window.SB_STATE && SB_STATE.provider, values: Object.keys((window.SB_STATE||{}).values||{})})));
console.log("errors:", errs);
await page.close(); await b.close();
