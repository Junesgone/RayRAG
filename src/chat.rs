/// `form_conversation` — mirror of `generator.py::full_question`:
/// `USER: ...\nASSISTANT: ...` lines from user/assistant messages.
pub fn form_conversation(messages: &[ChatMessage]) -> String {
    let mut lines = Vec::new();
    for m in messages {
        if m.role != "user" && m.role != "assistant" {
            continue;
        }
        lines.push(format!("{}: {}", m.role.to_uppercase(), m.content));
    }
    lines.join("\n")
}

/// Lightweight language detection used when `config.language` is unset:
/// CJK characters → `Chinese`, otherwise `English`.
pub fn detect_language(text: &str) -> String {
    if text.chars().any(|c| {
        matches!(c,
            '\u{4E00}'..='\u{9FFF}' | '\u{3400}'..='\u{4DBF}'
        )
    }) {
        "Chinese".into()
    } else {
        "English".into()
    }
}

/// Render `RAGFLOW_FULL_QUESTION_PROMPT` with today/yesterday/tomorrow as
/// absolute ISO dates plus the conversation and language hint.
pub fn build_full_question_prompt(conversation: &str, language: &str) -> String {
    let today = iso_date_shift(0);
    let yesterday = iso_date_shift(-1);
    let tomorrow = iso_date_shift(1);
    let mut vars = HashMap::new();
    vars.insert("today", today.as_str());
    vars.insert("yesterday", yesterday.as_str());
    vars.insert("tomorrow", tomorrow.as_str());
    vars.insert("conversation", conversation);
    vars.insert("language", language);
    PromptLibrary::full_question().render(&vars)
}

/// Render `RAGFLOW_MULTI_QUERIES_GEN_PROMPT`.
pub fn build_multi_queries_prompt(
    original_query: &str,
    original_question: &str,
    retrieved_docs: &str,
    missing_info: &str,
) -> String {
    let mut vars = HashMap::new();
    vars.insert("original_query", original_query);
    vars.insert("original_question", original_question);
    vars.insert("retrieved_docs", retrieved_docs);
    vars.insert("missing_info", missing_info);
    PromptLibrary::multi_queries_gen().render(&vars)
}

/// Render `RAGFLOW_CITATION_PLUS_PROMPT` with the citation guidelines as the
/// `{example}` block and the knowledge tree as `{sources}`.
pub fn build_citation_plus_prompt(sources: &str) -> String {
    let example = PromptLibrary::citation_prompt().render(&HashMap::new());
    let mut vars = HashMap::new();
    vars.insert("example", example.as_str());
    vars.insert("sources", sources);
    PromptLibrary::citation_plus().render(&vars)
}

/// Render `RAGFLOW_REFLECT_PROMPT` — `{goal}` plus one block per tool call.
pub fn build_reflect_prompt(goal: &str, tool_calls: &[(String, String)]) -> String {
    let calls = tool_calls
        .iter()
        .map(|(name, result)| format!("Tool call: `{name}`\nResults: {result}"))
        .collect::<Vec<_>>()
        .join("\n\n");
    let mut vars = HashMap::new();
    vars.insert("goal", goal);
    vars.insert("tool_calls", calls.as_str());
    PromptLibrary::reflect().render(&vars)
}

/// `kb_prompt` layout — mirror of `generator.py::kb_prompt` + the
/// `"\n------\n" + "\n\n------\n\n".join(...)` knowledge assembly from
/// `dialog_service.async_chat`. Each chunk renders as:
/// ```text
/// ID: 0
/// ├── Title: ...
/// └── Content:
/// <content>
/// ```
pub fn format_knowledge(hits: &[HybridSearchResult]) -> String {
    let knowledges: Vec<String> = hits
        .iter()
        .enumerate()
        .map(|(i, hit)| {
            let mut block = format!("\nID: {i}");
            if !hit.chunk.doc_name.is_empty() {
                block.push_str(&format!("\n├── Title: {}", hit.chunk.doc_name));
            }
            block.push_str("\n└── Content:\n");
            block.push_str(&hit.chunk.content);
            block
        })
        .collect();
    if knowledges.is_empty() {
        return String::new();
    }
    format!("\n------\n{}", knowledges.join("\n\n------\n\n"))
}

/// Assemble the generation messages: system prompt + knowledge tree +
/// (optional citation guidelines) + non-system history + user question.
pub fn build_answer_messages(
    config: &ChatPipelineConfig,
    question: &str,
    history: &[ChatMessage],
    knowledge: &str,
) -> Vec<ChatMessage> {
    let mut system = config
        .system_prompt
        .clone()
        .unwrap_or_else(|| DEFAULT_CHAT_SYSTEM_PROMPT.to_string());
    if !knowledge.trim().is_empty() {
        system.push_str("\n\nRelevant document context:\n");
        system.push_str(knowledge);
    }
    if config.citation_plus {
        system.push_str("\n\n");
        system.push_str(&PromptLibrary::citation_prompt().render(&HashMap::new()));
    }
    let mut msgs = vec![ChatMessage::new("system", system)];
    msgs.extend(history.iter().filter(|m| m.role != "system").cloned());
    msgs.push(ChatMessage::new("user", question));
    msgs
}

/// Parse the `multi_queries_gen` JSON output. Accepts the documented shape
/// `{"reasoning": ..., "questions": [{"question", "query"}, ...]}` and, as a
/// fallback, any embedded JSON array of `{question, query}` objects.
/// Returns an empty vector for malformed output.
pub fn parse_multi_queries(json: &str) -> Vec<MultiQuery> {
    let mut out = Vec::new();
    if let Ok(value) = serde_json::from_str::<serde_json::Value>(json)
        && let Some(questions) = value.get("questions").and_then(|q| q.as_array()) {
            collect_queries(questions, &mut out);
            return out;
        }
    // Fallback: extract the first bracketed JSON array.
    if let Some(start) = json.find('[')
        && let Some(end) = json.rfind(']')
            && end > start
                && let Ok(value) = serde_json::from_str::<serde_json::Value>(&json[start..=end])
                    && let Some(questions) = value.as_array() {
                        collect_queries(questions, &mut out);
                    }
    out
}

fn collect_queries(items: &[serde_json::Value], out: &mut Vec<MultiQuery>) {
    for item in items {
        let question = item.get("question").and_then(|v| v.as_str()).unwrap_or("");
        let query = item.get("query").and_then(|v| v.as_str()).unwrap_or("");
        if !question.is_empty() && !query.is_empty() {
            out.push(MultiQuery {
                question: question.to_string(),
                query: query.to_string(),
            });
        }
    }
}

/// Strip everything up to and including the last `</think>` marker —
/// mirror of RAGFlow `re.sub(r"^.*</think>", "", ans, flags=re.DOTALL)`.
pub fn strip_think(text: &str) -> String {
    match text.rfind("</think>") {
        Some(pos) => text[pos + "</think>".len()..].trim_start().to_string(),
        None => text.to_string(),
    }
}

fn chunk_reference(hit: &HybridSearchResult) -> serde_json::Value {
    serde_json::json!({
        "chunk_id": hit.chunk.id,
        "doc_name": hit.chunk.doc_name,
        "score": hit.score,
    })
}

/// ISO date `YYYY-MM-DD` shifted by `days` from today (UTC).
fn iso_date_shift(days: i64) -> String {
    let now = time::OffsetDateTime::now_utc() + time::Duration::days(days);
    format!(
        "{:04}-{:02}-{:02}",
        now.year(),
        now.month() as u8,
        now.day()
    )
}

fn env_flag(name: &str) -> bool {
    std::env::var(name)
        .map(|v| matches!(v.to_ascii_lowercase().as_str(), "1" | "true" | "on" | "yes"))
        .unwrap_or(false)
}

fn env_usize(name: &str) -> Option<usize> {
    std::env::var(name).ok().and_then(|v| v.trim().parse().ok())
}

fn env_f32(name: &str) -> Option<f32> {
    std::env::var(name).ok().and_then(|v| v.trim().parse().ok())
}

fn kb_flag(flags: &HashMap<String, String>, key: &str) -> bool {
    flags
        .get(key)
        .map(|v| matches!(v.to_ascii_lowercase().as_str(), "1" | "true" | "on" | "yes"))
        .unwrap_or(false)
}

fn kb_usize(flags: &HashMap<String, String>, key: &str) -> Option<usize> {
    flags.get(key).and_then(|v| v.trim().parse().ok())
}

fn kb_f32(flags: &HashMap<String, String>, key: &str) -> Option<f32> {
    flags.get(key).and_then(|v| v.trim().parse().ok())
}

